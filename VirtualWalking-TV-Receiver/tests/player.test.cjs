const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const java = fs.readFileSync(path.join(__dirname, '../app/src/main/java/de/virtualwalking/receiver/MainActivity.java'), 'utf8');
const origin = java.match(/PLAYER_ORIGIN = "([^"]+)"/)[1];
const method = java.slice(java.indexOf('    private String html()'), java.indexOf('    private void js('));
const expression = method.slice(method.indexOf('return ') + 7, method.lastIndexOf(';'));
const tokens = expression.match(/"(?:[^"\\]|\\.)*"|PLAYER_ORIGIN/g);
const page = tokens.map(token => token === 'PLAYER_ORIGIN' ? origin : JSON.parse(token)).join('');
assert.equal(origin, 'https://de.virtualwalking.receiver');
assert.match(page, /origin:'https:\/\/de.virtualwalking.receiver'/);
assert.match(page, /name='referrer' content='strict-origin-when-cross-origin'/);
assert.match(java, /loadDataWithBaseURL\(PLAYER_ORIGIN \+ "\/"/);
const code = page.match(/<script>([\s\S]*?)<\/script>/)[1];
const calls = [];
let options;
const player = Object.fromEntries(['loadVideoById','setPlaybackRate','pauseVideo','playVideo','seekTo'].map(name => [name, (...args) => calls.push([name,...args])]));
const context = vm.createContext({console,setInterval:()=>0,VWTvFeedback:{update(){}}, YT:{Player:function(id, config){options=config;return player;}}});
vm.runInContext(code, context);
context.vwPlay('abcdefghijk');
context.vwRate(1.5);
context.vwPause();
assert.deepEqual(calls, []);
context.onYouTubeIframeAPIReady();
assert.deepEqual(calls, []);
options.events.onReady();
assert.deepEqual(calls, [['loadVideoById','abcdefghijk'],['setPlaybackRate',1.5],['pauseVideo']]);
context.vwResume();
context.vwPlay('12345678901');
assert.deepEqual(calls.slice(-2), [['playVideo'],['loadVideoById','12345678901']]);
context.vwStop();assert.deepEqual(calls.slice(-2), [['pauseVideo'],['seekTo',0,true]]);
assert.match(java,/"\/stop"\.equals\(route\)/);
console.log('PASS: app identity, referrer, queued load/rate/pause, ready playback');
